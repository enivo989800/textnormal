package com.noteduo.textcaddy;

public final class GroupRecord {
    public String id;
    public String name;
    public int color;
    public int order;

    public GroupRecord(String id, String name, int color, int order) {
        this.id = id;
        this.name = name;
        this.color = color;
        this.order = order;
    }
}
